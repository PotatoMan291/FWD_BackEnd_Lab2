-- 1. TABLA DE INSUMOS
CREATE TABLE insumos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    unidad VARCHAR(20) NOT NULL
        CHECK (unidad IN ('g', 'ml', 'unidad')),
    stock NUMERIC(10, 2) NOT NULL DEFAULT 0
        CHECK (stock >= 0),
    stock_minimo NUMERIC(10, 2) NOT NULL DEFAULT 0
        CHECK (stock_minimo >= 0)
);

-- 2. TABLA DE PRODUCTOS
CREATE TABLE productos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    precio NUMERIC(10, 2) NOT NULL
        CHECK (precio > 0),
    categoria VARCHAR(50) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. TABLA DE RECETAS
-- Indica los insumos necesarios para cada producto.
CREATE TABLE recetas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id INTEGER NOT NULL
        REFERENCES productos(id) ON DELETE CASCADE,
    insumo_id INTEGER NOT NULL
        REFERENCES insumos(id) ON DELETE RESTRICT,
    cantidad NUMERIC(10, 2) NOT NULL
        CHECK (cantidad > 0),

    UNIQUE (producto_id, insumo_id)
);

-- 4. TABLA DE PEDIDOS (VENTAS)
CREATE TABLE pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    metodo_pago VARCHAR(20) NOT NULL
        CHECK (metodo_pago IN ('efectivo', 'tarjeta', 'sinpe')),
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (subtotal >= 0),
    impuesto NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (impuesto >= 0),
    total NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (total >= 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'confirmado'
        CHECK (estado IN ('confirmado', 'anulado'))
);

-- 5. TABLA DE DETALLES DE CADA PEDIDO
CREATE TABLE pedido_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL
        REFERENCES pedidos(id) ON DELETE CASCADE,
    producto_id INTEGER NOT NULL
        REFERENCES productos(id) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL
        CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL
        CHECK (precio_unitario > 0)
);

